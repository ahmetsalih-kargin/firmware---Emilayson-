"""A FirmAE tree in which the final emulation (scratch/<IID>/run.sh ->
scripts/emulate.sh) runs with every system command stubbed: no root, no QEMU,
no mount, loop device, TAP device or firewall. Shared by the run.sh tests.

The stubs append what they were called with to $LOG; iptables/ip6tables are
the ones from conftest.iptables_stubs. QEMU is a bash stand-in that logs its
start, optionally its arguments and environment, and exits after
QEMU_EXIT_AFTER seconds or when it gets SIGTERM.
"""

import os
import shutil
import signal
import subprocess
import time

from scripts import makeNetwork as mn

FAKE_QEMU = """#!/bin/bash
echo "qemu start $$" >> "$LOG"
if [ -n "${QEMU_LOG_ARGS:-}" ]; then
    echo "qemu args $*" >> "$LOG"
    echo "qemu argc $#" >> "$LOG"
    echo "qemu env QEMU_AUDIO_DRV=${QEMU_AUDIO_DRV-unset} ppid=$PPID" >> "$LOG"
fi
trap 'echo "qemu got TERM" >> "$LOG"; exit 0' TERM
if [ -n "${QEMU_EXIT_AFTER:-}" ]; then sleep "$QEMU_EXIT_AFTER"; echo "qemu exit" >> "$LOG"; exit 0; fi
while true; do sleep 0.1; done
"""

MODES = ("run.sh", "run_debug.sh", "run_analyze.sh", "run_boot.sh")


class World:
    def __init__(self, base, repo_root, iptables_stubs, iid=1):
        base.mkdir(parents=True, exist_ok=True)
        self.base = base
        self.iid = iid
        self.root = base / "FirmAE"
        self.work = self.root / "scratch" / str(iid)
        self.image = self.work / "image"
        (self.image / "firmadyne").mkdir(parents=True)
        (self.root / "scripts").mkdir()
        shutil.copy(str(repo_root / "scripts" / "emulate.sh"), str(self.root / "scripts"))
        self.log = base / "log"
        # firmae.config as shipped, plus stand-ins for the two helpers that need root
        text = (repo_root / "firmae.config").read_text()
        text += ('\nadd_partition () { [ -n "${FAIL_PARTITION:-}" ] && return 1; echo /dev/fakeloop0p1; }\n'
                 'del_partition () { echo "del_partition $1" >> "$LOG"; }\n')
        (self.root / "firmae.config").write_text(text)

        self.bindir = base / "bin"
        self.bindir.mkdir()
        rec = 'echo "$(basename $0) $*" >> "$LOG"'
        self.stub("sudo", 'exec "$@"')
        self.stub("mount", rec + '; [ -z "${FAIL_MOUNT:-}" ]')
        self.stub("umount", rec)
        self.stub("mountpoint", "exit 1")
        # FAIL_TUNCTL=1: creating any TAP device fails; =<name>: only that one
        self.stub("tunctl", rec + '; ! { [ -n "${FAIL_TUNCTL:-}" ] && [ "$1" = -t ] && '
                                  '{ [ "${FAIL_TUNCTL}" = 1 ] || [ "$2" = "${FAIL_TUNCTL}" ]; }; }')
        self.stub("ip", rec)
        for qemu in ("qemu-system-mipsel", "qemu-system-mips", "qemu-system-arm"):
            self.stub(qemu, FAKE_QEMU)
        self.rules = base / "rules"
        self.env = dict(os.environ, PATH="%s:%s" % (self.bindir, os.environ["PATH"]),
                        USER=os.environ.get("USER", "root"),
                        **iptables_stubs(self.bindir, self.log, self.rules))  # sets LOG, IPT_STATE
        self.env.pop("FIRMAE_DOCKER", None)
        for mode in MODES[1:]:      # as firmae/pipeline.py creates them
            os.symlink("./run.sh", str(self.work / mode))

    def stub(self, name, body):
        (self.bindir / name).write_text("#!/bin/bash\n" + body + "\n")
        (self.bindir / name).chmod(0o755)

    @property
    def run_sh(self):
        return self.work / "run.sh"

    @property
    def data(self):
        return self.work / mn.EMULATION_FILE

    def install(self, emulation):
        """The layout makeNetwork.py writes: run.sh wrapper + emulation.conf."""
        self.run_sh.write_text(mn.runShWrapper(self.iid))
        self.run_sh.chmod(0o755)
        self.data.write_text(emulation)

    def install_legacy(self, script):
        """A run.sh generated by the old template (tests/fixtures/legacy)."""
        self.run_sh.write_text(script)
        self.run_sh.chmod(0o755)

    def start(self, name="run.sh", cwd=None, argv0=None, background=False, **extra):
        """Start scratch/<IID>/<name>; by default as ./scratch/<IID>/<name>
        from the FirmAE directory (like run_mode.sh). background=True: as
        firmae/check.py starts it -- absolute path, stdin /dev/null, SIGINT
        and SIGQUIT ignored (bash cannot trap a signal ignored on entry)."""
        if argv0 is None:
            argv0 = ("./scratch/%d/%s" % (self.iid, name) if cwd is None and not background
                     else str(self.work / name))

        def ignore():
            signal.signal(signal.SIGINT, signal.SIG_IGN)
            signal.signal(signal.SIGQUIT, signal.SIG_IGN)
        return subprocess.Popen([argv0], cwd=str(cwd or self.root), env=dict(self.env, **extra),
                                stdin=subprocess.DEVNULL if background else None,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, start_new_session=True,
                                preexec_fn=ignore if background else None)

    def calls(self, firewall=False):
        """Logged commands; the firewall ones only when asked."""
        lines = self.log.read_text().splitlines() if self.log.exists() else []
        return [l for l in lines if firewall or not l.startswith(("iptables ", "ip6tables "))]

    def wait_for(self, text, timeout=15):
        for _ in range(int(timeout / 0.1)):
            if any(text in c for c in self.calls()):
                return
            time.sleep(0.1)
        raise AssertionError("never saw %r in %r" % (text, self.calls()))

    def guest_files(self):
        d = self.image / "firmadyne"
        return {p.name: p.read_text() for p in sorted(d.iterdir()) if p.is_file()}
